    "    def moderate(self, image: bytes) -> VisionResult:",
    "        im = Image.open(io.BytesIO(image)).convert('RGB').resize((24, 24))",
    "        px = list(im.getdata())",
    "        r = sum(p[0] for p in px) / len(px)",
    "        g = sum(p[1] for p in px) / len(px)",
    "        b = sum(p[2] for p in px) / len(px)",
